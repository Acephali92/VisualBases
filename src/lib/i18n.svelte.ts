const dicts: Record<Lang, Dict> = { de, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('vb-lang');
    if (saved === 'de' || saved === 'en') return saved;
  } catch { /* storage unavailable */ }
  if (typeof navigator !== 'undefined' && !navigator.language?.toLowerCase().startsWith('de')) return 'en';
  return 'de';
}

export const i18n = $state({ lang: initialLang() as Lang });

export function setLang(l: Lang) {
  i18n.lang = l;
  try { localStorage.setItem('vb-lang', l); } catch { /* ignore */ }
  document.documentElement.lang = l;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[i18n.lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

const regionNames: Partial<Record<Lang, Intl.DisplayNames>> = {};
export function countryName(cc: string | null | undefined): string {
  if (!cc) return '–';
  const l = i18n.lang;
  regionNames[l] ??= new Intl.DisplayNames([l], { type: 'region' });
  try { return regionNames[l]!.of(cc) ?? cc; } catch { return cc; }
}

export function formatNumber(n: number, digits = 0): string {
  return n.toLocaleString(i18n.lang === 'de' ? 'de-DE' : 'en-GB', { maximumFractionDigits: digits });
}
